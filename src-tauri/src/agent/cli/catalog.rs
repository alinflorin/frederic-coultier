//! What each `fc` command is, in the words the agent will read. The flags come from the same
//! constants the commands parse with, and a test checks that every flag is described here.

use super::commands::*;
use super::reference::{Cmd, Opt};

const fn o(name: &'static str, arg: &'static str, text: &'static str) -> Opt {
    Opt { name, arg, text }
}

